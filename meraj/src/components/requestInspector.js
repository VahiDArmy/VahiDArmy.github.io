/**
 * The exact-request inspector.
 *
 * The "body" tab renders the archived `bodyText` byte-for-byte (HTML-escaped
 * only so a browser can display it). That same string was passed to fetch().
 */
import { escapeHtml, formatDateTime, formatTokens, copyText, download, byteLength, sha256, formatNumber } from '../utils.js';
import { icon } from '../ui/icons.js';
import { openModal } from '../ui/modal.js';
import { toast } from '../ui/toast.js';
import {
  snapshotBodyText,
  snapshotMessages,
  snapshotPayload,
  requestToCurl,
  describeMessageForInspector,
} from '../services/requestBuilder.js';
import { estimateTokens } from '../services/tokens.js';

function fact(label, value) {
  if (value === null || value === undefined || value === '') return '';
  return `<div class="request-fact"><dt>${escapeHtml(label)}</dt><dd>${escapeHtml(String(value))}</dd></div>`;
}

export async function openRequestInspector({ snapshot, preview = false, message = null, subtitle = '' }) {
  if (!snapshot) {
    toast({ title: 'No request snapshot', message: 'This message has no archived request body.', type: 'warning' });
    return null;
  }
  const bodyText = snapshotBodyText(snapshot);
  const payload = snapshotPayload(snapshot);
  const messages = snapshotMessages(snapshot);
  const fingerprint = snapshot.fingerprint || (await sha256(bodyText));
  const byteCount = snapshot.byte_count || byteLength(bodyText);
  const messageItems = messages.map(describeMessageForInspector);
  const sumTokens = messageItems.reduce((sum, item) => sum + item.tokens, 0);
  const stream = Boolean(snapshot.stream);

  const headerFacts = [
    fact('Model', snapshot.model_slug || payload?.model),
    fact('Created', formatDateTime(snapshot.created_at || new Date())),
    fact('Messages', `${messages.length} · ${formatTokens(sumTokens)} estimated tokens`),
    fact('Body size', `${formatNumber(byteCount)} bytes · ${formatNumber(bodyText.length)} chars`),
    fact('Streaming', stream ? 'stream: true' : 'stream flag absent / false'),
    fact('Word count', `${formatNumber(bodyText.split(/\s+/).filter(Boolean).length)}`),
  ]
    .filter(Boolean)
    .join('');

  const messageHtml = messageItems
    .map(
      (item) => `<section class="request-message request-message--${escapeHtml(item.role)}">
        <header><span class="request-role">${escapeHtml(item.role)}</span><span class="mono">${formatNumber(item.chars)} chars · ~${formatNumber(item.tokens)} tokens</span></header>
        <pre class="verbatim" tabindex="0">${escapeHtml(item.content)}</pre>
      </section>`,
    )
    .join('');

  const modal = openModal({
    title: preview ? 'Exact request preview' : 'Exact request body',
    subtitle:
      subtitle ||
      (preview
        ? 'Built from the current conversation and your draft. Nothing has been sent.'
        : 'Archived before sending. This is the full text that went to the API, not a reconstruction.'),
    size: 'xl',
    className: 'request-modal',
    body: `
      <div class="exact-banner ${preview ? 'exact-banner--preview' : 'exact-banner--archived'}">
        <span class="exact-banner__icon">${icon(preview ? 'eye' : 'shieldCheck', { size: 19 })}</span>
        <div>
          <strong>${preview ? 'Preview only — not sent.' : 'Exact archived body.'}</strong>
          <p>${preview ? 'This preview is generated by the same builder that sends the request. Press send to send this exact body.' : 'The string in the Body tab is the exact `bodyText` that was handed to fetch(). HTML escaping is display-only; copied text is unescaped and complete.'}</p>
        </div>
      </div>
      <div class="request-facts">${headerFacts}</div>
      <div class="request-fingerprint">
        <span>${icon('hash', { size: 14 })} SHA-256 of exact body</span>
        <code class="mono">${escapeHtml(fingerprint)}</code>
      </div>
      <div class="tabs" role="tablist" aria-label="Request views">
        <button type="button" class="tab is-active" role="tab" aria-selected="true" data-request-tab="body">Exact body</button>
        <button type="button" class="tab" role="tab" aria-selected="false" data-request-tab="messages">Messages (${messages.length})</button>
        <button type="button" class="tab" role="tab" aria-selected="false" data-request-tab="curl">cURL</button>
        <button type="button" class="tab" role="tab" aria-selected="false" data-request-tab="headers">Headers</button>
      </div>
      <div class="request-panels">
        <section class="request-panel is-active" data-request-panel="body">
          <p class="request-panel__note">Raw JSON body — every character preserved, including whitespace and ordering.</p>
          <pre class="verbatim verbatim--tall" data-exact-body tabindex="0">${escapeHtml(bodyText)}</pre>
        </section>
        <section class="request-panel" data-request-panel="messages" hidden>
          <p class="request-panel__note">Each message content verbatim, rendered as text. This is the same content carried by the JSON body above.</p>
          ${messageHtml || '<p class="muted">No messages in this request.</p>'}
        </section>
        <section class="request-panel" data-request-panel="curl" hidden>
          <p class="request-panel__note">The key is a shell placeholder. Copy this command and set <code>$OPENROUTER_API_KEY</code> yourself.</p>
          <pre class="verbatim verbatim--tall" data-curl tabindex="0">${escapeHtml(requestToCurl(snapshot))}</pre>
        </section>
        <section class="request-panel" data-request-panel="headers" hidden>
          <p class="request-panel__note">The Authorization header is intentionally never archived. The API key is not stored in Supabase, logs, or these snapshots.</p>
          <div class="header-table">
            ${(snapshot.headers || [])
              .map(
                (header) =>
                  `<div class="header-row"><span>${escapeHtml(header.name)}</span><code>${escapeHtml(header.value)}</code></div>`,
              )
              .join('')}
            <div class="header-row"><span>Origin</span><code>${escapeHtml(location.origin)}</code></div>
          </div>
          ${message?.error ? `<p class="request-panel__note request-panel__note--warn">This request finished with an error: ${escapeHtml(message.error.message || '')}</p>` : ''}
        </section>
      </div>
      ${preview ? `<p class="request-preview-hint">${snapshot.message_count ? `${snapshot.message_count} message(s) · ` : ''}Providing an exact preview before sending is part of the request workflow, not an approximation after the fact.</p>` : ''}
    `,
    actions: [
      {
        label: 'Download body',
        variant: 'ghost',
        icon: 'download',
        onClick: () => download(`meraj-request-${Date.now()}.json`, bodyText, 'application/json'),
      },
      {
        label: 'Copy exact body',
        variant: 'primary',
        icon: 'copy',
        onClick: async () => {
          const ok = await copyText(bodyText);
          toast(
            ok
              ? { title: 'Exact body copied', message: `${formatNumber(byteCount)} bytes — unabridged.`, type: 'success' }
              : { title: 'Clipboard unavailable', message: 'Your browser refused clipboard access. Select the body and copy manually.', type: 'error' },
          );
        },
      },
    ],
    footerNote: 'Request bodies are stored with their assistant message in Supabase. The OpenRouter API key is not included.',
  });

  modal.body.querySelectorAll('[data-request-tab]').forEach((button) => {
    button.addEventListener('click', () => {
      const target = button.dataset.requestTab;
      modal.body.querySelectorAll('[data-request-tab]').forEach((tab) => {
        const active = tab === button;
        tab.classList.toggle('is-active', active);
        tab.setAttribute('aria-selected', String(active));
      });
      modal.body.querySelectorAll('[data-request-panel]').forEach((panel) => {
        const active = panel.dataset.requestPanel === target;
        panel.hidden = !active;
        panel.classList.toggle('is-active', active);
      });
    });
  });

  const curl = modal.body.querySelector('[data-curl]');
  if (curl) curl.dataset.copyText = 'curl';
  return modal;
}

export function formatRequestTime(snapshot) {
  return formatDateTime(snapshot?.created_at || new Date());
}

export function requestSummary(snapshot) {
  if (!snapshot) return 'No request archived';
  const body = snapshotBodyText(snapshot);
  return `${formatNumber(snapshot.message_count || 0)} messages · ${formatNumber(byteLength(body))} bytes`;
}

export function estimateSnapshotTokens(snapshot) {
  const messages = snapshotMessages(snapshot);
  return messages.reduce((sum, message) => sum + estimateTokens(message.content || ''), 0);
}
