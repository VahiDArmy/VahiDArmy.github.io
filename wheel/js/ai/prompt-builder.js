/**
 * ساخت پرامپت - تأکید شدید روی فارسی + داستان‌پردازی طبیعی
 * @module promptBuilder
 */

const PromptBuilder = {
    buildStoryPrompt(context = {}) {
        const {
            winner = null,
            supportingCharacters = [],
            topic = '',
            items = [],
            type = 'provide',
            tone = 'funny',
            extras = '',
        } = context;

        const parts = [];

        parts.push(this._getMainInstruction(tone, topic));
        if (winner) parts.push(this._buildMainCharacterSection(winner));
        if (supportingCharacters.length > 0) parts.push(this._buildSupportingSection(supportingCharacters));
        if (items.length > 0) parts.push(this._buildItemsSection(items, type));
        if (extras && extras.trim()) parts.push(`## 📌 درخواست ویژه‌ی کاربر:\n${extras.trim()}`);
        parts.push(this._buildCraftGuidelines());
        parts.push(this._buildFinalRules());

        return parts.join('\n\n');
    },

    _getMainInstruction(tone, topic) {
        const toneMap = {
            funny: 'بامزه و طنزآمیز، با موقعیت‌های کمیک طبیعی و دیالوگ‌های خنده‌دار',
            epic: 'حماسی و پرکشش، با صحنه‌های بزرگ و احساسات عمیق',
            romantic: 'عاشقانه و احساسی، با لحظه‌های لطیف و دیالوگ‌های صمیمی',
            mystery: 'معمایی و پرکشش، با سرنخ‌های پنهان و فضایی مرموز',
            sarcastic: 'طعنه‌آمیز و باهوش، با کنایه‌های ظریف',
            absurd: 'سورئال و غیرمنتظره، با موقعیت‌های پوچ‌گرایانه',
        };
        const toneText = toneMap[tone] || toneMap.funny;

        let text = `🔴🔴🔴 **دستور قطعی و بدون استثنا** 🔴🔴🔴

**زبان خروجی: فقط و فقط فارسی.**
- حتی **یک کلمه** انگلیسی ننویس
- **هیچ** تحلیل، توضیح، یا reasoning ننویس
- فقط داستان بنویس
- از اولین حرف تا آخرین نقطه، فارسی

تو یک داستان‌نویس حرفه‌ای فارسی‌زبان هستی.

**وظیفه:** یک داستان **زنده و طبیعی** با لحن ${toneText} بنویس.

⚠️ **اصل طلایی:** داستان باید **جریان طبیعی** داشته باشد. هیچ المانی را به زور در داستان نگذار. اگر جایی منطقی نبود، حذفش کن.`;

        if (topic && topic.trim()) {
            text += `\n\n**موضوع پیشنهادی:** «${topic.trim()}» — جهت‌گیری کلی است، نه چارچوب سخت. اگر مسیر بهتری پیدا کردی، آزاد باش.`;
        }

        return text;
    },

    _buildMainCharacterSection(winner) {
        const name = winner.name || winner.label || 'شخصیت ناشناس';
        let text = `## 🎭 قهرمان داستان: «${name}»\n\n`;

        if (winner.description && winner.description.trim()) {
            text += `**ویژگی‌ها:**\n${winner.description}\n\n`;
            text += `**نکته کلیدی:** این شخصیت را **واقعاً زنده کن**. ویژگی‌هایش را **نشان بده**، نه اینکه بگویی. مثلاً اگر «خسته» است، نشان بده چطور روی مبل می‌افتد، چطور پلک می‌زند، یا چه جور حرف می‌زند.`;
        } else {
            text += `(شخصیتی زنده و باورپذیر برایش بساز که در طول داستان ثابت بماند.)`;
        }

        return text;
    },

    _buildSupportingSection(characters) {
        const lines = characters.map((c) => {
            let line = `- **${c.name}**`;
            if (c.description && c.description.trim()) line += ` — ${c.description}`;
            return line;
        });

        return `## 👥 شخصیت‌های کنار داستان:
${lines.join('\n')}

**نحوه استفاده:**
- این‌ها شخصیت‌های **واقعی** داستان هستند، نه اسم‌هایی در لیست
- هرکدام باید **طبیعی** وارد داستان شوند
- ویژگی‌هایشان باید در رفتار دیده شود
- ⚠️ اگر یکی نمی‌تواند طبیعی وارد شود، استفاده نکن
- **کیفیت مهم‌تر از حضور اجباری همه است**`;
    },

    _buildItemsSection(items, type) {
        const labels = items.map((it) => {
            const label = typeof it === 'string' ? it : it.label;
            return `- ${label}`;
        });

        let intro;
        if (type === 'receive') {
            intro = `## 🎁 آیتم‌هایی که قهرمان در پایان دریافت می‌کند:`;
        } else {
            intro = `## 🎁 آیتم‌هایی که قهرمان باید تهیه کند:`;
        }

        return `${intro}\n${labels.join('\n')}

**نحوه استفاده:**
- این‌ها نباید **به زور** در داستان ظاهر شوند
- بهترین حالت: بخشی از **مسیر داستان** باشند
- می‌توانند در ابتدا، میانه، یا پایان ظاهر شوند - نه همه با هم
- ⚠️ اگر آیتمی نمی‌تواند طبیعی وارد شود، **حذفش کن**
- **خواننده نباید حس کند داستان دارد یک لیست را رد می‌کند**`;
    },

    _buildCraftGuidelines() {
        return `## 🎨 راهنمای داستان‌نویسی حرفه‌ای:

**۱. با یک صحنه زنده شروع کن**
داستان را با یک لحظه مشخص شروع کن — نه با توضیح کلی.

**۲. «نشان بده» نه «بگو» (Show, don't tell)**
❌ «وحید خسته بود.»
✅ «وحید با پلک‌های سنگین به مانیتور زل زد و یک بار دیگر قهوه‌ی سرد را سر کشید.»

**۳. دیالوگ‌ها طبیعی باشند**
- آدم‌ها همان‌طور که در واقعیت حرف می‌زنند، حرف بزنند
- هر شخصیت باید **سبک حرف زدن خودش** را داشته باشد

**۴. حذف توضیحات اضافی**
هر جمله باید **چیزی به داستان اضافه کند**.

**۵. خط داستانی واضح**
مسئله → تلاش → پیچش → پایان

**۶. اشتباهات رایج را انجام نده**
- ❌ همه شخصیت‌ها را در یک خط نام نبر
- ❌ همه آیتم‌ها را در یک پاراگراف ذکر نکن
- ❌ از کلیشه استفاده نکن
- ❌ با «روزی روزگاری» شروع نکن

**۷. فضاسازی**
زمان، مکان، حال‌و‌هوا را با جزئیات کوتاه ولی زنده بساز.

**۸. پایان**
پایانی که غافلگیرکننده ولی منطقی باشد.`;
    },

    _buildFinalRules() {
        return `## ✅ چک‌لیست نهایی:

- 🔴🔴🔴 **زبان:** ۱۰۰٪ فارسی — **بدون حتی یک کلمه انگلیسی**
- 🔴 **فقط داستان:** هیچ reasoning یا تحلیل ننویس
- 🔴 **کیفیت مهم‌تر از کمیت:** اگر المانی جایش نمی‌شود، حذف کن
- ✅ **تیتر:** یک تیتر خلاقانه (با ##)
- ✅ **شخصیت اصلی:** واقعاً زنده و فعال
- ✅ **دیالوگ:** حداقل یک دیالوگ طبیعی
- ✅ **طول طبیعی**

🎯 **یادآوری نهایی:** تو یک **داستان‌نویس** هستی، نه یک پرکننده فرم. اولویت اول، **کیفیت داستان** است. اگر متن تو شامل یک کلمه انگلیسی یا یک خط تحلیل باشد، **رد شده‌ای**. فقط داستان فارسی بنویس.`;
    },

    getSystemPrompt() {
        const custom = AppState.get('settings.aiSystemPrompt');
        if (custom && custom.trim()) return custom;

        return `🔴 قوانین قطعی و بدون استثنا:

1. تمام خروجی تو باید ۱۰۰٪ به زبان فارسی باشد
2. حتی یک کلمه انگلیسی، عربی، یا هر زبان دیگر ننویس
3. هیچ reasoning، تحلیل، یا توضیح انگلیسی ننویس
4. فقط داستان بنویس — نه چیز دیگر
5. کیفیت داستان از هر چیز دیگری مهم‌تر است
6. «نشان بده» نه «بگو»
7. دیالوگ‌های طبیعی بنویس
8. از کلیشه پرهیز کن

اگر خروجی‌ات شامل متن غیرفارسی باشد، تلاش تو شکست خورده است.

**نقش تو:** یک داستان‌نویس حرفه‌ای فارسی‌زبان که داستان‌های زنده، باورپذیر و جذاب می‌نویسد.`;
    },

    estimateWords(text) {
        return (text || '').trim().split(/\s+/).length;
    },
};

window.PromptBuilder = PromptBuilder;