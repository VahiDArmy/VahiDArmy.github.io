/**
 * ساخت پرامپت - با تأکید بر داستان‌پردازی طبیعی
 * @module promptBuilder
 */

const PromptBuilder = {
    buildStoryPrompt(context = {}) {
        const {
            winner = null,
            supportingCharacters = [],
            topic = '',
            items = [],
            type = 'provide',
            tone = 'funny',
            extras = '',
        } = context;

        const parts = [];

        parts.push(this._getMainInstruction(tone, topic));
        if (winner) parts.push(this._buildMainCharacterSection(winner));
        if (supportingCharacters.length > 0) parts.push(this._buildSupportingSection(supportingCharacters));
        if (items.length > 0) parts.push(this._buildItemsSection(items, type));
        if (extras && extras.trim()) parts.push(this._buildExtrasSection(extras));
        parts.push(this._buildCraftGuidelines());
        parts.push(this._buildFinalRules());

        return parts.join('\n\n');
    },

    /**
     * دستور اصلی - با تأکید روی داستان‌پردازی
     */
    _getMainInstruction(tone, topic) {
        const toneMap = {
            funny: 'بامزه و طنزآمیز، با موقعیت‌های کمیک طبیعی و دیالوگ‌های خنده‌دار',
            epic: 'حماسی و پرکشش، با صحنه‌های بزرگ و احساسات عمیق',
            romantic: 'عاشقانه و احساسی، با لحظه‌های لطیف و دیالوگ‌های صمیمی',
            mystery: 'معمایی و پرکشش، با سرنخ‌های پنهان و فضایی مرموز',
            sarcastic: 'طعنه‌آمیز و باهوش، با کنایه‌های ظریف',
            absurd: 'سورئال و غیرمنتظره، با موقعیت‌های پوچ‌گرایانه',
        };
        const toneText = toneMap[tone] || toneMap.funny;

        let text = `🔴 **دستور قطعی:**

تو یک داستان‌نویس حرفه‌ای فارسی‌زبان هستی. تمام خروجی‌ات باید **۱۰۰٪ به زبان فارسی** باشد و **فقط داستان** بنویسی — بدون هیچ توضیح، تحلیل، یا reasoning.

**وظیفه:** یک داستان **واقعی و زنده** با لحن ${toneText} بنویس.

⚠️ **مهم‌ترین اصل:** داستان باید **طبیعی و روان** جریان داشته باشد. از هیچ المانی به زور استفاده نکن. اگر جایی منطقی نبود، آن را حذف کن یا طبیعی جایش بگذار.`;

        if (topic && topic.trim()) {
            text += `\n\n**موضوع پیشنهادی:** «${topic.trim()}» — این را به عنوان **جهت‌گیری کلی** در نظر بگیر، نه چارچوب سخت. اگر مسیر جذاب‌تری پیدا کردی، آزاد باش.`;
        }

        return text;
    },

    /**
     * شخصیت اصلی
     */
    _buildMainCharacterSection(winner) {
        const name = winner.name || winner.label || 'شخصیت ناشناس';
        let text = `## 🎭 قهرمان داستان: «${name}»\n\n`;

        if (winner.description && winner.description.trim()) {
            text += `**درباره‌ی این شخص:**\n${winner.description}\n\n`;
            text += `**نکته‌ی کلیدی:** این شخصیت را **واقعاً زنده کن**. ویژگی‌هایش را نشان بده، نه اینکه بگویی. مثلاً اگر «خسته» است، نشان بده که با چه شکلی روی مبل می‌افتد، چطور پلک می‌زند، یا چه جور حرف می‌زند. خواننده باید این شخص را **ببیند**، نه فقط بشنود.`;
        } else {
            text += `(توصیفی ثبت نشده - یک شخصیت زنده و باورپذیر برایش بساز که در طول داستان ثابت بماند.)`;
        }

        return text;
    },

    /**
     * شخصیت‌های فرعی - با تأکید بر طبیعی بودن
     */
    _buildSupportingSection(characters) {
        const lines = characters.map((c) => {
            let line = `- **${c.name}**`;
            if (c.description && c.description.trim()) {
                line += ` — ${c.description}`;
            }
            return line;
        });

        return `## 👥 شخصیت‌های کنار داستان:
${lines.join('\n')}

**چطور از این‌ها استفاده کن:**
- این‌ها شخصیت‌های **واقعی** داستان هستند، نه اسم‌هایی که در لیست باشند
- هرکدام باید **طبیعی** وارد داستان شوند — مثلاً در یک مکالمه، یک اتفاق، یا یک موقعیت
- ویژگی‌هایشان باید در رفتار دیده شود
- ⚠️ اگر یکی از این‌ها **نمی‌تواند طبیعی** وارد داستان شود، استفاده‌اش نکن — اشکالی ندارد
- **مهم:** کیفیت حضور یک شخصیت مهم‌تر از حضور اجباری همه‌ی آن‌هاست`;
    },

    /**
     * آیتم‌ها - با تأکید بر طبیعی بودن
     */
    _buildItemsSection(items, type) {
        const labels = items.map((it) => {
            const label = typeof it === 'string' ? it : it.label;
            return `- ${label}`;
        });

        let intro;
        if (type === 'receive') {
            intro = `## 🎁 آیتم‌هایی که قهرمان در پایان دریافت می‌کند:`;
        } else {
            intro = `## 🎁 آیتم‌هایی که قهرمان باید تهیه کند:`;
        }

        return `${intro}\n${labels.join('\n')}

**چطور از این‌ها استفاده کن:**
- این‌ها نباید **به زور** در داستان ظاهر شوند
- بهترین حالت: بخشی از **مسیر داستان** باشند — مثلاً چیزی که دنبالش می‌رود، یا چیزی که وقتی به دستش می‌آید، داستان را جلو می‌برد
- می‌تواند یک آیتم در ابتدا، یک در میانه، و یکی در پایان ظاهر شود — نه همه با هم
- ⚠️ اگر آیتمی نمی‌تواند طبیعی وارد داستان شود، **حذفش کن** — اجباری نیست همه در داستان باشند
- **مهم:** خواننده نباید حس کند داستان دارد یک **لیست** را رد می‌کند`;
    },

    _buildExtrasSection(extras) {
        return `## 📌 درخواست ویژه‌ی کاربر:
${extras.trim()}`;
    },

    /**
     * راهنمای داستان‌پردازی - بخش جدید و مهم
     */
    _buildCraftGuidelines() {
        return `## 🎨 راهنمای داستان‌نویسی حرفه‌ای:

**۱. با یک صحنه‌ی زنده شروع کن**
داستان را با یک لحظه‌ی مشخص شروع کن — نه با توضیح کلی. مثل:
- یک دیالوگ که فضا را می‌سازد
- یک حرکت که شخصیت را نشان می‌دهد
- یک اتفاق کوچک که کنجکاوی برمی‌انگیزد

**۲. «نشان بده» نه «بگو» (Show, don't tell)**
❌ «وحید خسته بود.»
✅ «وحید با پلک‌های سنگین به مانیتور زل زد و یک بار دیگر قهوه‌ی سرد را سر کشید.»

**۳. دیالوگ‌ها طبیعی باشند**
- آدم‌ها در داستان، همان‌طور که در واقعیت حرف می‌زنند، حرف بزنند
- جمله‌های کوتاه، مکث‌ها، لحن‌های مختلف
- هر شخصیت باید **سبک حرف زدن خودش** را داشته باشد

**۴. حذف توضیحات اضافی**
- از توصیف‌های طولانی و بی‌ربط پرهیز کن
- هر جمله باید **چیزی به داستان اضافه کند** — وگرنه حذفش کن

**۵. خط داستانی واضح**
- یک **مسئله** در ابتدا
- **تلاش** برای حل آن
- یک **پیچش** یا اتفاق غیرمنتظره
- **پایان**ی که رضایت‌بخش باشد

**۶. اشتباهات رایج را انجام نده**
- ❌ همه‌ی شخصیت‌ها را در یک خط نام نبر
- ❌ همه‌ی آیتم‌ها را در یک پاراگراف ذکر نکن
- ❌ از کلمات تکراری و جمله‌های کلیشه‌ای استفاده نکن
- ❌ داستان را به زور به موضوع بچسبان
- ❌ با «یک روز...» یا «روزی روزگاری...» شروع نکن

**۷. فضاسازی**
- زمان، مکان، و حال‌و‌هوا را با جزئیات کوتاه ولی زنده بساز
- خواننده باید **حس کند** کجاست

**۸. پایان**
- پایانی که غافلگیرکننده باشد ولی منطقی
- بهتر است آخرین جمله، یک **تصویر** در ذهن خواننده بگذارد`;
    },

    /**
     * اصول نهایی
     */
    _buildFinalRules() {
        return `## ✅ چک‌لیست نهایی:

- 🔴 **زبان:** ۱۰۰٪ فارسی — بدون هیچ کلمه انگلیسی یا متن مختلط
- 🔴 **فقط داستان:** هیچ reasoning یا تحلیل انگلیسی ننویس
- 🔴 **کیفیت مهم‌تر از کمیت:** اگر نمی‌توانی المانی را طبیعی جایش بگذاری، حذفش کن
- ✅ **تیتر:** یک تیتر خلاقانه (با ## شروع کن)
- ✅ **پاراگراف‌بندی:** هر پاراگراف با یک خط خالی جدا شود
- ✅ **شخصیت اصلی:** واقعاً زنده و فعال
- ✅ **دیالوگ:** حداقل یک دیالوگ طبیعی در داستان
- ✅ **طول طبیعی:** نه خیلی کوتاه، نه خیلی طولانی — جایی که داستان تمام می‌شود

🎯 **یادآوری مهم:** تو یک **داستان‌نویس** هستی، نه یک پرکننده‌ی فرم. اولویت اول، کیفیت داستان است. اگر المانی در داستان جایش نمی‌شود، آن را حذف کن. خواننده باید داستان را **حس کند**، نه اینکه لیست المان‌ها را ببیند.`;
    },

    getSystemPrompt() {
        const custom = AppState.get('settings.aiSystemPrompt');
        if (custom && custom.trim()) return custom;

        return `تو یک داستان‌نویس حرفه‌ای، خلاق و فارسی‌زبان هستی.

🔴 **قوانین قطعی:**
1. تمام خروجی تو باید ۱۰۰٪ به زبان فارسی باشد
2. فقط داستان بنویس — هیچ reasoning، تحلیل، یا توضیح انگلیسی
3. کیفیت داستان از هر چیز دیگری مهم‌تر است
4. اگر المانی در داستان جایش نمی‌شود، حذفش کن
5. «نشان بده» نه «بگو»
6. دیالوگ‌های طبیعی بنویس
7. از کلیشه پرهیز کن

**نقش تو:** نوشتن داستان‌های زنده، باورپذیر و جذاب.`;
    },

    estimateWords(text) {
        return (text || '').trim().split(/\s+/).length;
    },
};

window.PromptBuilder = PromptBuilder;