let currentLang = 'fa';

export function getLanguage() {
  return currentLang;
}

export function setLanguage(lang) {
  const id = ['fa', 'en'].includes(lang) ? lang : CONFIG.defaults.language || 'fa';
  currentLang = id;
  return currentLang;
}

/**
 * Translate a key. Supports simple {name} interpolation.
 * Falls back to English, then to the key itself.
 */
export function t(key, vars = {}) {
  const dict = dictionaries[currentLang] || dictionaries.fa;
  let text = dict[key] ?? dictionaries.en[key] ?? key;
  if (vars && typeof vars === 'object') {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value ?? ''));
    }
  }
  return text;
}

export function languageMeta(id = currentLang) {
  return (CONFIG.languages || []).find((item) => item.id === id) || CONFIG.languages?.[0] || { id: 'fa', dir: 'rtl', htmlLang: 'fa' };
}

/** Expose dictionaries for tooling / completeness checks. */
export function listKeys(lang = 'fa') {
  return Object.keys(dictionaries[lang] || {});
}
