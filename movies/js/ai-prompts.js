  function analysisUser(data) {
    const lines = ['لیست تماشای من:', '', '**عاشقشم (❤️):**'];

    data.love.forEach(function (t) {
      let s = '- ' + t.title;
      if (t.year) s += ' (' + t.year + ')';
      if (t.genre) s += ' — ' + t.genre;
      lines.push(s);
    });

    lines.push('', '**خوب (👍):**');
    data.good.forEach(function (t) {
      let s = '- ' + t.title;
      if (t.year) s += ' (' + t.year + ')';
      if (t.genre) s += ' — ' + t.genre;
      lines.push(s);
    });

    lines.push('', '**دری وری (👎):**');
    data.hate.forEach(function (t) {
      let s = '- ' + t.title;
      if (t.year) s += ' (' + t.year + ')';
      if (t.genre) s += ' — ' + t.genre;
      lines.push(s);
    });

    lines.push('');
    lines.push('---');
    lines.push('');
    lines.push('## ۱. الگوهای مشترک در عاشقشم‌ها');
    lines.push('## ۲. مرزِ «خوب» و «عاشقشم»');
    lines.push('## ۳. ریشه‌ی «دری وری»ها');
    lines.push('## ۴. نویسنده یا سازنده‌های همسو');
    lines.push('## ۵. پیشنهاد فیلم');
    lines.push('## ۶. پیشنهاد سریال');

    return lines.join('\n');
  }

