  function analysisUser(data) {
    const lines = ['لیست تماشای من:', ''];
    const groups = [
      ['5', 'شاهکار'],
      ['4', 'خوب'],
      ['3', 'خنثی'],
      ['2', 'ضعیف'],
      ['1', 'متنفرم']
    ];
    groups.forEach(function (g) {
      const n = Number(g[0]);
      const items = data.all.filter(function (t) { return Math.floor(t.rating || 0) === n; });
      if (!items.length) return;
      lines.push('**' + g[1] + ':**');
      items.forEach(function (t) {
        let s = '- ' + t.title;
        if (t.year) s += ' (' + t.year + ')';
        if (t.genre) s += ' — ' + t.genre;
        lines.push(s);
      });
      lines.push('');
    });
    lines.push('---');
    lines.push('');
    lines.push('## ۱. الگوهای مشترک در آثار ۵ ستاره');
    lines.push('## ۲. مرز ۵ ستاره و ۴ ستاره');
    lines.push('## ۳. ریشه‌ی آثار ۱ و ۲ ستاره — کدام قواعد روایی نقض شده؟');
    lines.push('## ۴. نویسنده‌ها یا سازنده‌های همسو');
    lines.push('## ۵. پیشنهاد فیلم');
    lines.push('## ۶. پیشنهاد سریال');
    return lines.join('\n');
  }

